  return (
    <html
      lang="en"
      className={`${inter.variable} ${playfair.variable} ${firaCode.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        {children}
        <Analytics />
      </body>
    </html>
  );
